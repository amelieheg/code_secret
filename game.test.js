'use strict';
const assert = require('assert');
const { PALETTE, score, createGame } = require('./game');
assert.deepStrictEqual(PALETTE, ['rouge', 'bleu', 'vert', 'jaune', 'orange', 'violet']);
assert.deepStrictEqual(score(['rouge', 'rouge', 'bleu', 'vert'], ['rouge', 'bleu', 'rouge', 'rouge']), { exact: 1, misplaced: 2 });
assert.deepStrictEqual(score(['rouge', 'rouge', 'bleu', 'bleu'], ['bleu', 'bleu', 'rouge', 'rouge']), { exact: 0, misplaced: 4 });
assert.deepStrictEqual(score(['rouge', 'bleu', 'vert', 'jaune'], ['rouge', 'rouge', 'rouge', 'rouge']), { exact: 1, misplaced: 0 });
const game = createGame(() => 0);
const initial = game.getState();
assert.strictEqual(initial.secret, null);
for (const invalid of [null, [], ['rouge'], ['rouge', null, 'rouge', 'rouge'], ['rouge', 'rouge', 'rouge', 'rose'], ['Rouge', 'rouge', 'rouge', 'rouge'], new Array(4)]) {
  assert.strictEqual(game.submit(invalid).ok, false);
  assert.deepStrictEqual(game.getState(), initial);
}
for (let i = 0; i < 9; i++) assert.strictEqual(game.submit(['bleu', 'bleu', 'bleu', 'bleu']).state.status, 'playing');
assert.strictEqual(game.submit(['rouge', 'rouge', 'rouge', 'rouge']).state.status, 'won');
assert.strictEqual(game.getState().attempts, 10);
const won = game.getState();
assert.strictEqual(game.submit(['bleu', 'bleu', 'bleu', 'bleu']).ok, false);
assert.deepStrictEqual(game.getState(), won);
game.newGame();
assert.deepStrictEqual(game.getState(), initial);
const guess = ['bleu', 'bleu', 'bleu', 'bleu'];
game.submit(guess);
guess[0] = 'rouge';
assert.strictEqual(game.getState().history[0].guess[0], 'bleu');
const snapshot = game.getState();
snapshot.history[0].guess[0] = 'vert';
assert.strictEqual(game.getState().history[0].guess[0], 'bleu');
for (let i = 1; i < 10; i++) game.submit(['bleu', 'bleu', 'bleu', 'bleu']);
assert.strictEqual(game.getState().status, 'lost');
assert.deepStrictEqual(game.getState().secret, ['rouge', 'rouge', 'rouge', 'rouge']);
const lost = game.getState();
assert.strictEqual(game.submit(['rouge', 'rouge', 'rouge', 'rouge']).ok, false);
assert.deepStrictEqual(game.getState(), lost);
let draws = 0;
const randomGame = createGame(() => { draws++; return .999; });
assert.strictEqual(draws, 4);
randomGame.submit(['violet', 'violet', 'violet', 'violet']);
assert.strictEqual(randomGame.getState().status, 'won');
randomGame.newGame();
assert.strictEqual(draws, 8);
console.log('Tous les tests sont passés : doublons, validation, dixième essai, fin de partie et réinitialisation.');
